#!/usr/bin/env python3
"""Share WGT highlighting captures between Tree-sitter consumers and Zed."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    vocab = json.loads((ROOT / 'editors/vocabulary.json').read_text())
    words = lambda key: ' '.join(json.dumps(word) for word in vocab[key])
    highlights = '''; Generated by scripts/generate_tree_sitter_queries.py.
(identifier) @variable
(comment) @comment
(string) @string
(number) @number
(operator) @operator
(punctuation) @punctuation.delimiter
["(" ")" "[" "]"] @punctuation.bracket
["model" "block" "layer" "input" "output" "const" "dim"] @keyword
["wgt" "require" "use" "import" "inherit" "freeze" "unfreeze" "data" "init" "train" "config" "parameter" "share" "adapter" "return"] @keyword
(clause) @keyword
(call function: (qualified_name) @function)
(parameter name: (identifier) @variable.parameter)
(model_declaration name: (identifier) @type)
(block_declaration name: (identifier) @function)
(constant_declaration name: (identifier) @constant)
(dimension_declaration name: (identifier) @type)
'''
    highlights += f'((identifier) @type.builtin (#any-of? @type.builtin {words("types")}))\n'
    highlights += f'((qualified_name . (identifier) @function.builtin .) (#any-of? @function.builtin {words("builtins")}))\n'
    files = {'highlights.scm': highlights,
             'brackets.scm': '(arguments "(" @open ")" @close)\n(array "[" @open "]" @close)\n',
             'indents.scm': '(arguments ")" @end) @indent\n(array "]" @end) @indent\n',
             'outline.scm': '\n'.join(f'({node}_declaration name: (identifier) @name) @item' for node in ['model', 'block', 'layer', 'port', 'constant', 'dimension']) + '\n'}
    return {ROOT / prefix / name: content for prefix in ['editors/tree-sitter-wgt/queries', 'editors/zed/languages/wgt'] for name, content in files.items()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, f'Stale query: {path.relative_to(ROOT)}\n')
        else:
            path.write_text(content)
