#!/usr/bin/env node
'use strict';
// Check coverage without building Rust. The Rust match remains exhaustive too.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
assert.ok(process.argv.slice(2).every(arg => arg === '--write'), 'Only --write is accepted');
const root = path.resolve(__dirname, '..');
const catalogPath = path.join(root, 'language/tensor_contracts.json');
const outputPath = path.join(root, 'crates/wgt-language/src/adaptive/contract_catalog.rs');
const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
assert.equal(catalog.schema_version, 1);
const rows = catalog.operators;
assert.ok(Array.isArray(rows) && rows.length > 0);
const names = new Set(), variants = new Set();
const fields = ['variant', 'name', 'min_ir_version', 'shape', 'layout', 'gradient', 'effect'];
for (const row of rows) {
  assert.deepEqual(Object.keys(row).sort(), [...fields].sort());
  assert.match(row.variant, /^[A-Z][A-Za-z0-9]*$/);
  assert.match(row.name, /^[a-z][a-z0-9_]*$/);
  assert.ok([1, 2, 3].includes(row.min_ir_version));
  assert.ok(!names.has(row.name) && !variants.has(row.variant), 'duplicate operator');
  names.add(row.name); variants.add(row.variant);
  for (const field of fields.filter(f => f !== 'min_ir_version')) {
    assert.equal(typeof row[field], 'string'); assert.ok(row[field].length > 0);
  }
}
const quote = text => JSON.stringify(text);
const entries = rows.map(r => `    OperatorContract { name: ${quote(r.name)}, min_ir_version: ${r.min_ir_version}, shape: ${quote(r.shape)}, layout: ${quote(r.layout)}, gradient: ${quote(r.gradient)}, effect: ${quote(r.effect)} },`).join('\n');
const arms = rows.map((r, i) => `            Self::${r.variant} { .. } => &OPERATOR_CONTRACTS[${i}],`).join('\n');
const generated = `// Generated by scripts/check_tensor_contracts.cjs --write; do not edit.\npub const OPERATOR_CONTRACTS: &[OperatorContract] = &[\n${entries}\n];\n\nimpl Instruction {\n    pub fn contract(&self) -> &'static OperatorContract {\n        match self {\n${arms}\n        }\n    }\n}\n`;
if (process.argv.includes('--write')) {
  fs.writeFileSync(outputPath, generated);
} else {
  assert.equal(fs.readFileSync(outputPath, 'utf8'), generated, 'contract catalog needs regeneration');
}
const source = fs.readFileSync(path.join(root, 'crates/wgt-language/src/adaptive.rs'), 'utf8');
const declaration = source.slice(source.indexOf('pub enum Instruction {'));
assert.ok(declaration.startsWith('pub enum Instruction {'));
const declared = [...declaration.matchAll(/^    ([A-Z][A-Za-z0-9]*)\s*\{/gm)].map(m => m[1]);
assert.deepEqual([...new Set(declared)].sort(), [...variants].sort(), 'IR instruction inventory drift');
console.log(`Tensor catalog: ${rows.length} unique instruction contracts; generated file matches.`);
