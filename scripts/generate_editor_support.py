#!/usr/bin/env python3
"""Generate editor assets from one vocabulary; no WeightLang/Torch import needed."""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import plistlib
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]


def vocabulary():
    tree = ast.parse((ROOT / 'src/weightlang/syntax.py').read_text())
    groups = {'keywords': {'as', 'from'}, 'builtins': {'mean', 'sum', 'transpose', 'residual'}, 'types': set()}
    names = {'PARAM_FREE_OPS', 'ARG_OPS', 'GRAPH_OPS', 'LOOP_OPS', 'LOSSES', 'OPTIMIZERS', 'BUILTIN_OPS'}
    # Collect literal additions as well as initial definitions, without executing the parser.
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith('_stmt_'):
            groups['keywords'].add(node.name[6:])
        value = None
        target = None
        if isinstance(node, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
            target = node.targets[0] if isinstance(node, ast.Assign) else node.target
            value = node.value
        if isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name) and target.value.id in names:
            if isinstance(target.slice, ast.Constant):
                groups['builtins'].add(target.slice.value)
        if isinstance(target, ast.Name) and target.id in names | {'DTYPES'}:
            parts = [value]
            if isinstance(value, ast.BinOp):
                parts = [n for n in ast.walk(value) if isinstance(n, ast.Set)]
            values = [v for part in parts for v in (part.keys if isinstance(part, ast.Dict) else part.elts if isinstance(part, ast.Set) else [])]
            groups['types' if target.id == 'DTYPES' else 'builtins'].update(
                v.value for v in values if isinstance(v, ast.Constant) and isinstance(v.value, str))
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name):
            if node.func.value.id in names and node.func.attr == 'update' and node.args and isinstance(node.args[0], ast.Dict):
                groups['builtins'].update(k.value for k in node.args[0].keys if isinstance(k, ast.Constant))
    return {key: sorted(value) for key, value in groups.items()}


def outputs():
    vocab = vocabulary()
    alt = {k: '|'.join(v) for k, v in vocab.items()}
    number = r'(?<![\w.])-?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?(?![\w.])'
    patterns = [
        {'name': 'comment.line.number-sign.wgt', 'match': '#.*$'},
        {'name': 'string.quoted.double.wgt', 'begin': '"', 'end': '"|$'},
        {'name': 'keyword.control.wgt', 'match': r'\b(?:' + alt['keywords'] + r')\b'},
        {'name': 'storage.type.wgt', 'match': r'\b(?:' + alt['types'] + r')\b'},
        {'name': 'variable.parameter.wgt', 'match': r'\b[A-Za-z_]\w*(?=\s*=)'},
        {'name': 'support.function.wgt', 'match': r'(?<![\w.])(?:' + alt['builtins'] + r')\b'},
        {'name': 'constant.numeric.wgt', 'match': number},
        {'name': 'entity.name.function.wgt', 'match': r'\b[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?(?=\s*\()'},
        {'name': 'keyword.operator.wgt', 'match': r'->|//|[=+*/%\-]'},
        {'name': 'punctuation.wgt', 'match': r'[\[\](),.:]'},
    ]
    grammar = {'name': 'WeightLang', 'scopeName': 'source.wgt', 'fileTypes': ['wgt'], 'patterns': patterns}
    result = {
        'editors/vocabulary.json': json.dumps(vocab, indent=2) + '\n',
        'editors/vscode/syntaxes/wgt.tmLanguage.json': json.dumps(grammar, indent=2) + '\n',
        'editors/WeightLang.tmbundle/Syntaxes/WeightLang.tmLanguage': plistlib.dumps(grammar).decode(),
        'editors/WeightLang.tmbundle/info.plist': plistlib.dumps({'name': 'WeightLang', 'uuid': 'BE6969BD-D858-4FA1-90BA-623632E08912'}).decode(),
    }
    vim = ['" Generated by scripts/generate_editor_support.py', 'if exists("b:current_syntax") | finish | endif']
    for group, words in vocab.items():
        vim.append('syntax keyword wgt' + group.title() + ' ' + ' '.join(words))
    vim += [
        r'syntax match wgtNumber /\v<\d+(\.\d*)?([eE][+-]?\d+)?/',
        r'syntax match wgtNumber /\v\.\d+([eE][+-]?\d+)?/',
        r'syntax match wgtOperator /\v-\>|\/\/|[=+*\/%-]/',
        r'syntax match wgtParameter /\v<[A-Za-z_][A-Za-z0-9_]*\ze\s*\=/',
        r'syntax region wgtString start=/"/ end=/"/ oneline',
        r'syntax match wgtComment /#.*/',
    ]
    for group, style in {'Keywords': 'Keyword', 'Builtins': 'Function', 'Types': 'Type', 'Number': 'Number', 'String': 'String', 'Comment': 'Comment', 'Operator': 'Operator', 'Parameter': 'Identifier'}.items():
        vim.append(f'hi def link wgt{group} {style}')
    vim.append('let b:current_syntax = "wgt"')
    result['editors/vim/syntax/wgt.vim'] = '\n'.join(vim) + '\n'
    result['editors/vim/ftdetect/wgt.vim'] = 'augroup weightlang_filetype\n  autocmd!\n  autocmd BufRead,BufNewFile *.wgt setfiletype wgt\naugroup END\n'
    result['editors/vim/ftplugin/wgt.vim'] = r'''if exists("b:did_ftplugin") | finish | endif
let b:did_ftplugin = 1
setlocal commentstring=#\ %s comments=:#
let b:undo_ftplugin = "setlocal commentstring< comments<"
'''
    el = [';;; wgt-mode.el --- WeightLang highlighting -*- lexical-binding: t; -*-', ';; Generated by scripts/generate_editor_support.py', '(require \'prog-mode)', '(defvar wgt-mode-syntax-table', '  (let ((table (make-syntax-table)))', '    (modify-syntax-entry ?# "<" table)', '    (modify-syntax-entry ?\\n ">" table)', '    (modify-syntax-entry ?_ "w" table)', '    (modify-syntax-entry ?\\\" "\\\"" table)', '    table))', '(defvar wgt-font-lock-keywords', '  (list']
    for group, face in [('keywords', 'font-lock-keyword-face'), ('builtins', 'font-lock-builtin-face'), ('types', 'font-lock-type-face')]:
        words = ' '.join(json.dumps(w) for w in vocab[group])
        el.append(f'    (cons (regexp-opt \'({words}) \'symbols) \'{face})')
    el += ['    (cons "\\\\_<[0-9]+\\\\(?:\\\\.[0-9]*\\\\)?\\\\(?:[eE][-+]?[0-9]+\\\\)?\\\\_>" \'font-lock-constant-face)))', ';;;###autoload', '(define-derived-mode wgt-mode prog-mode "WGT"', '  "Highlight WeightLang model sources; does not validate or execute them."', '  :syntax-table wgt-mode-syntax-table', '  (setq-local font-lock-defaults \'(wgt-font-lock-keywords))', '  (setq-local comment-start "# ")', '  (setq-local comment-end ""))', ';;;###autoload', '(add-to-list \'auto-mode-alist \'("\\\\.wgt\\\\\'" . wgt-mode))', "(provide 'wgt-mode)", ';;; wgt-mode.el ends here']
    result['editors/emacs/wgt-mode.el'] = '\n'.join(el) + '\n'
    kate = ['<?xml version="1.0" encoding="UTF-8"?>', '<!DOCTYPE language SYSTEM "language.dtd">', '<language name="WeightLang" version="1" kateversion="5.0" section="Sources" extensions="*.wgt" mimetype="text/x-wgt" author="WeightLang contributors" license="MIT">', '<highlighting>']
    for group, words in vocab.items():
        kate.append(f'<list name="{group}">' + ''.join(f'<item>{word}</item>' for word in words) + '</list>')
    kate += ['<contexts><context name="Normal" attribute="Normal" lineEndContext="#stay">', '<DetectChar char="#" attribute="Comment" context="Comment"/>', '<DetectChar char="&quot;" attribute="String" context="String"/>']
    for group in vocab:
        kate.append(f'<keyword String="{group}" attribute="{group}" context="#stay"/>')
    kate += [f'<RegExpr String="{escape(number, {chr(34): "&quot;"})}" attribute="Number" context="#stay"/>', '</context>', '<context name="Comment" attribute="Comment" lineEndContext="#pop"/>', '<context name="String" attribute="String" lineEndContext="#pop"><DetectChar char="&quot;" attribute="String" context="#pop"/></context>', '</contexts><itemDatas>']
    for name, style in {'Normal':'dsNormal','keywords':'dsKeyword','builtins':'dsFunction','types':'dsDataType','Number':'dsDecVal','String':'dsString','Comment':'dsComment'}.items():
        kate.append(f'<itemData name="{name}" defStyleNum="{style}"/>')
    kate += ['</itemDatas></highlighting><general><comments><comment name="singleLine" start="#"/></comments><keywords casesensitive="1"/></general></language>']
    result['editors/kate/wgt.xml'] = '\n'.join(kate) + '\n'
    gtk = ['<?xml version="1.0" encoding="UTF-8"?>', '<language id="wgt" name="WeightLang" version="2.0" _section="Source">', '<metadata><property name="globs">*.wgt</property><property name="line-comment-start">#</property></metadata>', '<styles><style id="keywords" name="Keyword" map-to="def:keyword"/><style id="builtins" name="Builtin" map-to="def:function"/><style id="types" name="Type" map-to="def:type"/></styles>', '<definitions><context id="wgt"><include>', '<context id="comment" class="comment" style-ref="def:comment" end-at-line-end="true"><start>#</start></context>', '<context id="string" class="string" style-ref="def:string" end-at-line-end="true"><start>"</start><end>"</end></context>']
    for group, words in vocab.items():
        gtk.append(f'<context id="{group}" style-ref="{group}">' + ''.join(f'<keyword>{word}</keyword>' for word in words) + '</context>')
    gtk += [f'<context id="number" style-ref="def:decimal"><match>{escape(number)}</match></context>', '</include></context></definitions></language>']
    result['editors/gtksourceview/wgt.lang'] = '\n'.join(gtk) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if committed editor assets are stale')
    args = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode():
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Regenerate editor support: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
