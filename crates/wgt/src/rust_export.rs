//! Export a checked model definition as an embeddable Rust architecture module.
//!
//! The shared frontend resolves pure imports. Generated Rust embeds that complete
//! source and uses the `wgt-model` facade; computation remains in the native service.
use anyhow::{Context, Result, ensure};
use std::{io::Write, path::Path};
use wgt_language::model::ModelDefinition;
use wgt_language::backend::{Backend, preflight_source};

pub const DEFAULT_CRATE_PATH: &str = "::wgt";

/// Validate a file and embed its complete pure model dependency closure.
/// This does not materialize parameters, evaluate forward, or contact a service.
pub fn compile(path: &Path, crate_path: &str) -> Result<String> {
    compile_with_dimensions(path, crate_path, &Default::default())
}

pub fn compile_with_dimensions(path: &Path, crate_path: &str, dimensions: &wgt_language::dimensions::Dimensions) -> Result<String> {
    validate_crate_path(crate_path)?;
    // ModelDefinition performs Rust preflight before resolving file imports,
    // retaining its bounded regular-file reader and original diagnostic lines.
    let definition = ModelDefinition::from_file_with_dimensions(path, dimensions)
        .with_context(|| format!("invalid model definition {}", path.display()))?;
    Ok(render(&definition, crate_path))
}

/// Validate and embed an in-memory definition. Relative imports require a file;
/// standard pure model imports are resolved by the shared frontend in both modes.
pub fn compile_source(source: &str, crate_path: &str) -> Result<String> {
    compile_source_with_dimensions(source, crate_path, &Default::default())
}

pub fn compile_source_with_dimensions(source: &str, crate_path: &str, dimensions: &wgt_language::dimensions::Dimensions) -> Result<String> {
    validate_crate_path(crate_path)?;
    preflight_source(source, Backend::Rust).context("invalid model definition")?;
    let definition = ModelDefinition::parse_with_dimensions(source, dimensions).context("invalid model definition")?;
    Ok(render(&definition, crate_path))
}

fn render(definition: &ModelDefinition, crate_path: &str) -> String {
    // Rust's Debug string representation escapes quotes, backslashes, controls
    // and Unicode correctly, without the delimiter limits of raw string literals.
    let source = format!("{:?}", definition.source());
    format!(
        "// Generated by wgt compile --target rust.\n\
         // Architecture only; execution uses the wgt-model native service API.\n\
         // Pure imports are embedded. No WGT source files are needed at runtime.\n\n\
         /// Self-contained WGT architecture, including its declared initializers.\n\
         pub const SOURCE: &str = {source};\n\n\
         /// Parse the embedded architecture without initialization or execution.\n\
         /// The facade version must support the language used by this definition.\n\
         pub fn definition() -> {crate_path}::Result<{crate_path}::ModelDefinition> {{\n    {crate_path}::ModelDefinition::parse(SOURCE)\n}}\n"
    )
}

/// Allow an external ASCII Rust path, including a renamed dependency or reexport,
/// without allowing generated Rust expressions or statements in the crate path.
fn validate_crate_path(path: &str) -> Result<()> {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
        "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
        "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe",
        "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do",
        "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
        "gen",
    ];
    let external = path.strip_prefix("::").unwrap_or(path);
    ensure!(
        external.split("::").all(|segment| {
            let (identifier, raw) = segment
                .strip_prefix("r#")
                .map_or((segment, false), |identifier| (identifier, true));
            let mut chars = identifier.chars();
            identifier != "_"
                && chars
                    .next()
                    .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
                && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
                && if raw {
                    !["crate", "self", "super", "Self"].contains(&identifier)
                } else {
                    !KEYWORDS.contains(&identifier)
                }
        }),
        "invalid Rust facade crate path; use an external ASCII path such as ::wgt or renamed_wgt"
    );
    Ok(())
}

/// Atomically publish a new Rust source file; never overwrite an existing path.
pub fn write(module: &str, output: &Path) -> Result<()> {
    let parent = output
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let mut stage = tempfile::NamedTempFile::new_in(parent)?;
    stage.write_all(module.as_bytes())?;
    stage.persist_noclobber(output).with_context(|| {
        format!(
            "cannot create {} (existing files are never overwritten)",
            output.display()
        )
    })?;
    Ok(())
}

#[cfg(test)]
mod backend_tests {
    use super::*;

    #[test]
    fn torch_compatibility_reports_backend_boundary_for_source_and_file() {
        let source = "# compatibility model\nwgt 0.5\ntarget torch\nhost demo\n";
        let error = compile_source(source, DEFAULT_CRATE_PATH).unwrap_err();
        assert_boundary(&error);
        let root = std::env::temp_dir().join("weightlang");
        std::fs::create_dir_all(&root).unwrap();
        let directory = tempfile::tempdir_in(root).unwrap();
        let path = directory.path().join("model.wgt");
        std::fs::write(&path, source).unwrap();
        let error = compile(&path, DEFAULT_CRATE_PATH).unwrap_err();
        assert_boundary(&error);
        assert!(error.to_string().contains(&path.display().to_string()));
    }

    fn assert_boundary(error: &anyhow::Error) {
        let message = format!("{error:#}");
        for expected in ["line 3:", "Python/PyTorch", "Rust backend", "shared WGT"] {
            assert!(message.contains(expected), "{message}");
        }
    }
}
