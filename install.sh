#!/bin/sh
# Prepare uv and Rust, then install the native WeightLang tools.
set -eu

fail() { printf 'WeightLang: %s\n' "$*" >&2; exit 1; }
usable() { command -v "$1" >/dev/null 2>&1 && "$1" --version >/dev/null 2>&1; }
quote() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
absolute() { case "$1" in /*) printf '%s\n' "$1" ;; *) printf '%s/%s\n' "$PWD" "$1" ;; esac; }
add_path() {
    case ":${PATH:-}:" in *":$1:"*) ;; *) PATH="${PATH:+$PATH:}$1" ;; esac
    export PATH
}
download() {
    if command -v curl >/dev/null 2>&1; then
        curl --proto '=https' --tlsv1.2 -fsSL "$1" -o "$2"
    elif command -v wget >/dev/null 2>&1; then
        wget -qO "$2" "$1"
    else
        fail 'Install curl or wget to download uv and Rust.'
    fi
}

[ -n "${HOME:-}" ] || fail 'HOME must be set.'
CARGO_HOME=$(absolute "${CARGO_HOME:-"$HOME/.cargo"}")
RUSTUP_HOME=$(absolute "${RUSTUP_HOME:-"$HOME/.rustup"}")
weightlang_root=$(absolute "${CARGO_INSTALL_ROOT:-"$CARGO_HOME"}")
weightlang_uv=${UV_INSTALL_DIR:-${XDG_BIN_HOME:-}}
if [ -z "$weightlang_uv" ]; then
    if [ -n "${XDG_DATA_HOME:-}" ]; then weightlang_uv="$XDG_DATA_HOME/../bin"
    else weightlang_uv="$HOME/.local/bin"; fi
fi
weightlang_uv=$(absolute "$weightlang_uv")
export CARGO_HOME RUSTUP_HOME
add_path "$weightlang_uv"
add_path "$CARGO_HOME/bin"
add_path "$weightlang_root/bin"

weightlang_tmp=''
trap '[ -z "$weightlang_tmp" ] || rm -rf "$weightlang_tmp"' EXIT
trap 'exit 1' HUP INT TERM
prepare_download() {
    if [ -z "$weightlang_tmp" ]; then
        mkdir -p "${TMPDIR:-/tmp}/weightlang"
        weightlang_tmp=$(mktemp -d "${TMPDIR:-/tmp}/weightlang/install.XXXXXX")
    fi
}

if ! usable uv; then
    printf '%s\n' 'Installing uv...'
    prepare_download
    download https://astral.sh/uv/install.sh "$weightlang_tmp/uv.sh" || fail 'Could not download the uv installer.'
    UV_INSTALL_DIR="$weightlang_uv" UV_NO_MODIFY_PATH=1 sh "$weightlang_tmp/uv.sh" || fail 'uv installation failed.'
fi
usable uv || fail 'uv is not usable after installation.'

if ! usable cargo || ! usable rustc; then
    printf '%s\n' 'Installing the minimal stable Rust toolchain (including Cargo)...'
    if usable rustup; then
        rustup toolchain install stable --profile minimal || fail 'Rust toolchain installation failed.'
        if ! rustup default >/dev/null 2>&1; then
            rustup default stable || fail 'Could not select the stable Rust toolchain.'
        fi
    else
        prepare_download
        download https://sh.rustup.rs "$weightlang_tmp/rustup.sh" || fail 'Could not download the Rust installer.'
        sh "$weightlang_tmp/rustup.sh" -y --profile minimal --default-toolchain stable --no-modify-path || fail 'Rust installation failed.'
    fi
fi
usable cargo && usable rustc || fail 'Rust/Cargo is unavailable. Check rustup show and any project toolchain override.'

# One shared environment file keeps repeated installs and shell startup idempotent.
weightlang_config=$(absolute "${XDG_CONFIG_HOME:-"$HOME/.config"}")
weightlang_env="$weightlang_config/weightlang/env"
mkdir -p "$weightlang_config/weightlang"
{
    printf '%s\n' '# WeightLang tool environment. Generated by install.sh.'
    printf 'export CARGO_HOME=${CARGO_HOME:-%s}\n' "$(quote "$CARGO_HOME")"
    printf 'export RUSTUP_HOME=${RUSTUP_HOME:-%s}\n' "$(quote "$RUSTUP_HOME")"
    printf 'for _weightlang_bin in %s "$CARGO_HOME/bin" %s; do\n' "$(quote "$weightlang_uv")" "$(quote "$weightlang_root/bin")"
    cat <<'ENV'
    case ":${PATH:-}:" in
        *":$_weightlang_bin:"*) ;;
        *) PATH="${PATH:+$PATH:}$_weightlang_bin" ;;
    esac
done
export PATH
unset _weightlang_bin
ENV
} > "$weightlang_env"
weightlang_hook=". $(quote "$weightlang_env")"
add_profile() {
    if ! grep -Fqx "$weightlang_hook" "$1" 2>/dev/null; then
        printf '\n# WeightLang tools\n%s\n' "$weightlang_hook" >> "$1"
    fi
}
add_profile "$HOME/.profile"
add_profile "$HOME/.bashrc"
for weightlang_profile in "$HOME/.bash_profile" "$HOME/.bash_login"; do
    [ ! -f "$weightlang_profile" ] || add_profile "$weightlang_profile"
done
mkdir -p "${ZDOTDIR:-$HOME}"
add_profile "${ZDOTDIR:-$HOME}/.zshenv"
mkdir -p "$weightlang_config/fish/conf.d"
{
    printf '%s\n' '# WeightLang tool environment. Generated by install.sh.'
    printf 'set -q CARGO_HOME; or set -gx CARGO_HOME %s\n' "$(quote "$CARGO_HOME")"
    printf 'set -q RUSTUP_HOME; or set -gx RUSTUP_HOME %s\n' "$(quote "$RUSTUP_HOME")"
    printf 'for _weightlang_bin in %s "$CARGO_HOME/bin" %s\n' "$(quote "$weightlang_uv")" "$(quote "$weightlang_root/bin")"
    printf '%s\n' '    contains -- "$_weightlang_bin" $PATH; or set -gx PATH $PATH "$_weightlang_bin"' 'end'
} > "$weightlang_config/fish/conf.d/weightlang.fish"

# Cargo otherwise builds remote installs in a temporary directory, often tmpfs.
CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-"${XDG_CACHE_HOME:-"$HOME/.cache"}/weightlang/install/target"}
export CARGO_TARGET_DIR
set -- install --locked --force --root "$weightlang_root" --bin weightc --bin wgt
if [ -n "${WEIGHTLANG_SOURCE:-}" ]; then
    set -- "$@" --path "$WEIGHTLANG_SOURCE/crates/wgt"
elif [ -f crates/wgt/Cargo.toml ]; then
    set -- "$@" --path crates/wgt
elif [ -n "${WEIGHTLANG_VERSION:-}" ]; then
    set -- "$@" --git https://github.com/WeightLang/WeightLang.git --tag "$WEIGHTLANG_VERSION" weightlang-wgt
else
    set -- "$@" --git https://github.com/WeightLang/WeightLang.git --branch main weightlang-wgt
fi
cargo "$@" || fail 'WeightLang compilation failed. Check the Cargo error above; use a current Rust toolchain (rustup update stable) and a system C/C++ linker.'

uv --version
cargo --version
rustc --version
_WGT_VERSION_PROBE=1 "$weightlang_root/bin/wgt" --version
_WGT_VERSION_PROBE=1 "$weightlang_root/bin/weightc" --version
printf '\n%s\n' 'Installed uv, Cargo, wgt and weightc. New terminals load the configured PATH.'
printf 'For this terminal, run: . %s\n' "$(quote "$weightlang_env")"
